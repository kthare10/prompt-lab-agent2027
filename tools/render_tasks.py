#!/usr/bin/env python3
"""Render tasks/*.yaml into the prompt appendix carried by PLAN.md and the artifact.

The prompts live in `tasks/` and nowhere else. This regenerates the copies in
the documents from those files, so the two cannot drift — the same reason the
deliverable checklist is parsed from the skill's own frontmatter rather than
restated.

    python3 tools/render_tasks.py --markdown   # rewrites PLAN.md between markers
    python3 tools/render_tasks.py --html       # prints the artifact section
    python3 tools/render_tasks.py --check      # non-zero exit if PLAN.md is stale
"""

from __future__ import annotations

import argparse
import glob
import html
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = "<!-- BEGIN TASK PROMPTS (generated by tools/render_tasks.py — do not edit by hand) -->"
END = "<!-- END TASK PROMPTS -->"


def tasks() -> list[dict]:
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, "tasks", "*.yaml"))):
        with open(path) as fh:
            d = yaml.safe_load(fh)
        d["_file"] = os.path.relpath(path, ROOT)
        out.append(d)
    return out


def _answers(t: dict) -> list[tuple[str, str]]:
    return list((t.get("sim_answers") or {}).items())


def markdown() -> str:
    lines = [BEGIN, ""]
    for t in tasks():
        skill = f"`/{t['skill']}`" if t.get("skill") else "no skill"
        lines += [
            f"### {t['id']} — {t['title']}",
            "",
            f"`{t['tier']}` · exposure `{t['exposure']}` · {skill} · agent `{t['agent']}` · "
            f"depth `{t['depth']}` · project `{t['project']}` · [`{t['_file']}`]({t['_file']})",
            "",
            "> " + "\n> ".join(t["prompt"].rstrip().split("\n")),
            "",
        ]
        ans = _answers(t)
        if ans:
            lines += ["When the assistant asks, the user simulator replies:", ""]
            lines += [f"- **{k}** — “{v}”" for k, v in ans]
            lines += [""]
    lines.append(END)
    return "\n".join(lines)


def html_section() -> str:
    parts = []
    for t in tasks():
        skill = f"/{t['skill']}" if t.get("skill") else "no skill"
        fam = t["exposure"]
        ans = "".join(
            f"<li><b>{html.escape(k)}</b> — “{html.escape(v)}”</li>" for k, v in _answers(t)
        )
        ans_block = f'<div class="fix"><b>User simulator replies</b><ul class="sim">{ans}</ul></div>' if ans else ""
        parts.append(f'''      <div class="task">
        <h4><span class="tid">{html.escape(t['id'])}</span> {html.escape(t['title'])}</h4>
        <div class="tmeta">{html.escape(t['tier'])} · {fam} · {html.escape(skill)} · agent {html.escape(t['agent'])} · depth {html.escape(t['depth'])}</div>
        <blockquote>{html.escape(t['prompt'].rstrip())}</blockquote>
        {ans_block}
      </div>''')
    return "\n".join(parts)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--html", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    if args.html:
        print(html_section())
        return

    plan = os.path.join(ROOT, "PLAN.md")
    with open(plan) as fh:
        text = fh.read()
    block = markdown()

    if BEGIN not in text:
        sys.exit(f"{plan} has no {BEGIN!r} marker — add one where the appendix belongs.")
    updated = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)

    if args.check:
        sys.exit(0 if updated == text else "PLAN.md prompt appendix is stale — run tools/render_tasks.py --markdown")

    with open(plan, "w") as fh:
        fh.write(updated)
    print(f"PLAN.md appendix regenerated from {len(tasks())} task files")


if __name__ == "__main__":
    main()
